// Inlines everything in public/ into src/static.js so the Worker serves the site itself.
// Runs automatically before `wrangler dev` / `wrangler deploy` (see "build" in wrangler.jsonc).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { extname, join } from "node:path";

const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".svg": "image/svg+xml",
  ".json": "application/json",
  ".txt": "text/plain; charset=utf-8",
};

const files = {};
for (const name of readdirSync("public")) {
  const type = TYPES[extname(name)];
  if (!type) continue;
  files["/" + name] = { type, body: readFileSync(join("public", name), "utf8") };
}
files["/"] = files["/index.html"];

writeFileSync(
  "src/static.js",
  "// Generated by scripts/bundle-static.mjs — do not edit.\nexport default " + JSON.stringify(files) + ";\n"
);
console.log(`Bundled ${Object.keys(files).length - 1} files from public/`);
